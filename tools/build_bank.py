"""Validate tools/bank_src.py (including arithmetic checks) and write data/bank.js.

Run from the project folder:  python3 tools/build_bank.py [--json FILE [--batch NAME] [--min-level N]]
"""
import json
import math
import re
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from bank_src import QUESTIONS  # noqa: E402

OUT = HERE.parent / "data" / "bank.js"
BUNDLED_BATCHES = {"base", "fundamentals-2"}  # extra batches are exported as importable .json files instead
LEADING_NUMBER = re.compile(r"^\s*([-−]?\d+(?:\.\d+)?)")
# "option B", "answer C", or an "A) ..." style label (but not a unit like "(A)" for ampere)
LETTER_REF = re.compile(r"\b(?:option|answer|choice)\s+[A-D]\b|(?:^|\s)[A-D]\)\s", re.I)


def leading_number(text):
    m = LEADING_NUMBER.match(text)
    return float(m.group(1).replace("−", "-")) if m else None


def unit_of(text):
    m = LEADING_NUMBER.match(text)
    return text[m.end():].strip().lower() if m else None


def close(a, b, tol):
    return abs(a - b) <= tol * max(abs(b), 1e-12)


def validate(item):
    errors = []
    qid = item["id"]
    opts = item["options"]
    if len(opts) != 4 or len({o.strip().lower() for o in opts}) != 4 or any(not o.strip() for o in opts):
        errors.append("needs exactly 4 distinct, non-empty options")
    if item["correct_index"] not in range(4):
        errors.append("correct_index must be 0-3")
    if LETTER_REF.search(item["explanation"]):
        errors.append("explanation refers to options by letter (they are shuffled)")
    if item["check"] and not errors:
        expr, tol = item["check"]
        value = eval(expr, {"__builtins__": {}}, {"pi": math.pi})  # noqa: S307 - trusted local file
        right = leading_number(opts[item["correct_index"]])
        if right is None:
            errors.append("check given but correct option has no leading number")
        elif not close(value, right, tol):
            errors.append(f"ARITHMETIC: {expr} = {value:.6g} but the correct option says {right:g}")
        right_unit = unit_of(opts[item["correct_index"]])
        for i, other in enumerate(opts):
            if i != item["correct_index"]:
                n = leading_number(other)
                # same number with a different unit (e.g. "300 W" for work) is a deliberate trap
                if n is not None and close(value, n, tol) and unit_of(other) == right_unit:
                    errors.append(f"option {other!r} also matches the computed value {value:.6g}")
    return [f"{qid}: {e}" for e in errors]


def main():
    problems = []
    ids = Counter(item["id"] for item in QUESTIONS)
    problems += [f"duplicate id {i}" for i, n in ids.items() if n > 1]
    for item in QUESTIONS:
        problems += validate(item)
    if problems:
        print("BANK PROBLEMS:")
        print("\n".join(" - " + p for p in problems))
        sys.exit(1)

    def strip(item):
        return {k: v for k, v in item.items() if k not in ("check", "batch")}

    clean = [strip(i) for i in QUESTIONS if i["batch"] in BUNDLED_BATCHES]

    # Optional: --json FILE writes a file you can import on the phone (Settings > Add more questions),
    # so new questions do not require re-uploading the app. Add --min-level N to export only harder ones.
    if "--json" in sys.argv:
        target = Path(sys.argv[sys.argv.index("--json") + 1])
        min_level = int(sys.argv[sys.argv.index("--min-level") + 1]) if "--min-level" in sys.argv else 1
        batch = sys.argv[sys.argv.index("--batch") + 1] if "--batch" in sys.argv else None
        chosen = [strip(i) for i in QUESTIONS if i["level"] >= min_level and (batch is None or i["batch"] == batch)]
        target.write_text(json.dumps({"questions": chosen}, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"Wrote {len(chosen)} questions (level >= {min_level}, batch {batch or 'any'}) to {target}")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(
        "// Generated by tools/build_bank.py. Do not edit by hand.\n"
        "self.ENG_BANK = " + json.dumps(clean, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    checked = sum(1 for i in QUESTIONS if i["check"])
    print(f"OK: {len(QUESTIONS)} questions valid ({checked} arithmetic-checked); {len(clean)} bundled into {OUT.name}")
    for (level, topic), n in sorted(Counter((i["level"], i["topic"]) for i in QUESTIONS).items()):
        print(f"  level {level} {topic}: {n}")


if __name__ == "__main__":
    main()
